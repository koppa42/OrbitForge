"""Generate exact rational, order-12 summed Gauss-Jackson/Adams coefficients.

Berry & Healy (2004), equations 20-26, 52-53, 69-70, 77-89:
https://hdl.handle.net/1903/2202
This script derives coefficients with Fraction; it does not copy a library table.
Usage: python tools/validation/gauss_jackson_coefficients.py [--check]
"""
from fractions import Fraction as F
from math import comb
from pathlib import Path
import sys


def coefficients(order):
    # c(d) = -d/log(1-d), d is the backward difference operator.
    c = [F(1)]
    for n in range(1, order + 3):
        c.append(-sum(c[i] / F(n - i + 1) for i in range(n)))
    position = [sum(c[i] * c[k + 2 - i] for i in range(k + 3))
                for k in range(order + 1)]
    velocity = [F(0)] + c[2:order + 2]
    position_predict = [sum(position[:k + 1]) for k in range(order + 1)]
    velocity_predict = [F(1, 2) + sum(velocity[:k + 1]) for k in range(order + 1)]
    def ordinate(d):
        return [(-1)**j * sum(d[k] * comb(k, j) for k in range(j, len(d)))
                for j in range(len(d))]
    return [ordinate(d) for d in (position, velocity, position_predict, velocity_predict)]


def render():
    tables = coefficients(12)
    assert [sum(c) for c in tables] == [F(1, 12), 0, F(1, 12), F(1, 2)]
    # Independent published eighth-order endpoint and predictor entries, Tables 5/6.
    eight = coefficients(8)
    assert eight[0][0] == F(3250433, 53222400)
    assert eight[2][0] == F(103798439, 159667200)
    # Exact polynomial consistency of both recurrences, not floating point fitting.
    def correction(c, power, at):
        return sum(w * F(at - j)**power for j, w in enumerate(c))
    for power in range(13):
        a, b, ap, bp = tables
        s0 = -correction(b, power, 0)
        S0 = -correction(a, power, 0)
        s1 = s0 + (F(0)**power + F(1)) / 2
        S1 = S0 + s0 + F(0)**power / 2
        assert s1 + correction(b, power, 1) == F(1, power + 1)
        assert S1 + correction(a, power, 1) == F(1, (power + 1)*(power + 2))
        assert s0 + F(0)**power/2 + correction(bp, power, 0) == F(1, power + 1)
        assert S1 + correction(ap, power, 0) == F(1, (power + 1)*(power + 2))
    lines = ['// Generated by tools/validation/gauss_jackson_coefficients.py.',
             '// Newest acceleration first. Exact rational derivation and moment checks.',
             '// Berry & Healy (2004), https://hdl.handle.net/1903/2202.']
    for name, values in zip(('gj_position', 'gj_velocity', 'gj_position_predict',
                              'gj_velocity_predict'), tables):
        lines.append('constexpr std::array<double, 13> ' + name + '{')
        lines += ['    '+str(x.numerator)+'.0 / '+str(x.denominator)+'.0,' for x in values]
        lines.append('};')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    path = Path(__file__).resolve().parents[2] / 'modules/core/src/propagation/integrators/gauss_jackson_coefficients.inc'
    content = render()
    if '--check' in sys.argv:
        assert path.read_text(encoding='utf-8') == content, 'Coefficient file differs from exact derivation'
    else:
        path.write_text(content, encoding='utf-8', newline='\n')
    print('Gauss-Jackson: four rational tables and 52 polynomial moment identities verified')
